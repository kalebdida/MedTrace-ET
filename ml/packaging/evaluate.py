"""Validation-only threshold selection; untouched source-group test evaluation."""

import json, time
import numpy as np
import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt
from sklearn.metrics import (
    roc_curve,
    roc_auc_score,
    precision_recall_fscore_support,
    confusion_matrix,
    accuracy_score,
)
from augment import ROOT, PACKAGE
from visual_model import load


def main():
    rows = json.loads((ROOT / "data/manifest.json").read_text())
    model = load()
    for r in rows:
        if r["split"] != "train":
            r["score"] = model.similarity((ROOT / r["path"]).read_bytes(), r["gtin"])
    val = [r for r in rows if r["split"] == "validation"]
    test = [r for r in rows if r["split"] == "test"]
    genuine = np.array([r["score"] for r in val if not r["label"]])
    # Low similarity means counterfeit; quantiles are points on empirical genuine FPR curve.
    mismatch = float(np.quantile(genuine, 0.01, method="lower"))
    match_threshold = float(np.quantile(genuine, 0.05))
    thresholds = {"VISUAL_MISMATCH_BELOW": mismatch, "VISUAL_MATCH_AT": match_threshold}
    (PACKAGE / "thresholds.json").write_text(json.dumps(thresholds, indent=2) + "\n")
    y = np.array([r["label"] for r in test])
    scores = np.array([r["score"] for r in test])
    pred = scores < mismatch
    precision, recall, f1, _ = precision_recall_fscore_support(
        y, pred, average="binary", zero_division=0
    )
    fpr, tpr, _ = roc_curve(y, 1 - scores)
    plt.plot(fpr, tpr, label=f"AUC={roc_auc_score(y, 1 - scores):.3f}")
    plt.plot([0, 1], [0, 1], "--")
    plt.xlabel("Genuine false-alarm rate")
    plt.ylabel("Synthetic-defect recall")
    plt.legend()
    plt.tight_layout()
    plt.savefig(ROOT / "results/roc.png")
    plt.close()
    payload = (ROOT / test[0]["path"]).read_bytes()
    for _ in range(5):
        model.similarity(payload, test[0]["gtin"])
    latency = []
    for _ in range(100):
        start = time.perf_counter()
        model.similarity(payload, test[0]["gtin"])
        latency.append(1000 * (time.perf_counter() - start))
    results = {
        "thresholds": thresholds,
        "validation_genuine_count": len(genuine),
        "test_count": len(test),
        "auc": float(roc_auc_score(y, 1 - scores)),
        "accuracy": float(accuracy_score(y, pred)),
        "precision": float(precision),
        "recall": float(recall),
        "f1": float(f1),
        "confusion_matrix_tn_fp_fn_tp": confusion_matrix(y, pred).tolist(),
        "test_genuine_false_alarm_rate": float(pred[y == 0].mean()),
        "test_genuine_acceptance": float((scores[y == 0] >= match_threshold).mean()),
        "latency_ms_p50_p95": np.percentile(latency, [50, 95]).tolist(),
        "model_bytes": (PACKAGE / "model.onnx").stat().st_size,
        "per_defect": {
            kind: {
                "count": sum(r["defect"] == kind for r in test),
                "mismatch_rate": float(
                    np.mean(
                        [r["score"] < mismatch for r in test if r["defect"] == kind]
                    )
                ),
            }
            for kind in sorted({r["defect"] for r in test})
        },
    }
    (ROOT / "results/metrics.json").write_text(json.dumps(results, indent=2) + "\n")
    (ROOT / "results/predictions.json").write_text(
        json.dumps([r for r in rows if r["split"] != "train"], indent=2) + "\n"
    )
    (ROOT / "results/README.md").write_text(
        "# Synthetic packaging evaluation\n\nGenerated by `python ml/packaging/evaluate.py`. Positive class is synthetic defect. Thresholds selected only on validation captures: empirical 1% genuine false-alarm target (lower quantile), and 95% genuine acceptance target (5th percentile). With only "
        + str(len(genuine))
        + " genuine validation captures, these targets cannot establish population guarantees. Sources are disjoint across train, validation and test, but share three fictional designs. This is not evidence of real counterfeit detection.\n\n```json\n"
        + json.dumps(results, indent=2)
        + "\n```\n\nConfusion matrix rows: genuine/defect; columns: genuine/defect. Latency includes PNG decoding, preprocessing, CPU ONNX inference and cosine scoring, after 5 warmups, 100 runs, two ONNX threads. Cold start and Lambda latency are unmeasured. See roc.png and predictions.json for reproducible evidence. Match scores between thresholds are inconclusive.\n"
    )
    print(json.dumps(results, indent=2))


if __name__ == "__main__":
    main()
